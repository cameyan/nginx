# 软件包名称
pack_name="nginx"

# 自动构建
function auto_build() {
    echo "准备构建环境..."

    # 安装构建依赖
    dnf builddep -y "${pack_name}.spec"

    # 创建构建目录
    mkdir -p "$HOME/rpmbuild/SOURCES" "$HOME/rpmbuild/SPECS"

    # 复制源码文件和spec文件
    \cp -a -f -- * ~/rpmbuild/SOURCES
    \mv -f "$HOME/rpmbuild/SOURCES/${pack_name}.spec" "$HOME/rpmbuild/SPECS"

    echo "开始构建..."
    rpmbuild --noclean --nocheck  -ba "$HOME/rpmbuild/SPECS/${pack_name}.spec"
}

# 脚本帮助信息
function readme() {
    printf "
\033[32m用法:
    bash auto_run.sh [参数]

-b      使用源码包和spec文件进行rpm构建
-h      打印帮助信息\033[0m
"
}

# 入口函数
if [[ $# != 1 ]]
then
    readme
    exit
fi

while [[ $# -gt 0 ]]; do
    case "$1" in
        -b)
            auto_build
            ;;
        -h|--help)
            readme
            ;;
        *)
            printf "\033[31m错误: 存在无效参数，请检查...\033[0m\n"
            readme
            break
    esac
    shift  # 移动到下一个参数
done
